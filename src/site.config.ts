/** Ссылка на приложение. `campaign` попадает в отчёт App Store Connect, если указан providerToken. */
export function appStoreUrl(campaign = 'site') {
  const base = `https://apps.apple.com/app/id${APP.appStoreId}`;
  return APP.providerToken ? `${base}?pt=${APP.providerToken}&ct=${encodeURIComponent(campaign)}&mt=8` : base;
}

